const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { start } = require('./live-test-harness');
async function main() {
  const h = await start(), { page } = h;
  try {
    await page.setViewportSize({ width: 1400, height: 9000 });
    const fixture = fs.readFileSync(path.join(__dirname, '../docs/fixtures/extended-markdown-demo.md'), 'utf8').replace(/\r\n/g, '\n');
    await h.load(fixture);
    assert.equal(await page.locator('.lp-definition-list dl').count(), 2);
    assert(await page.locator('.lp-quote').count() > 0);
    assert.equal(await page.locator('.task-checkbox').count(), 6);
    assert.equal(await page.locator('.lp-html script, .lp-html iframe').count(), 0);
    assert(await page.locator('.lp-html details').count());
    await page.locator('.lp-html summary').click(); assert(await page.locator('.lp-html details').getAttribute('open') !== null);
    await page.locator('.task-checkbox').first().click(); await h.idle(); assert(h.text().includes('- [x] 待办事项一'));
    await page.locator('.lp-footnote button').first().click(); assert(await page.locator('#lpReturn').isVisible()); await page.locator('#lpReturn').click();
    await page.setViewportSize({ width: 1440, height: 1000 });
    const source = '\uFEFF---\ntags: [Project]\ndate: 2026-09-18\n---\n# 标题\n\n正文 **外层 *内部* 文本**。\n\n![示意](image.png)\n\n## 后节\n\n后文\n';
    await h.load(source); await page.evaluate(() => window.LivePreview.goto(window.LivePreview.bridge.text.indexOf('正文')));
    assert.equal(await page.locator('.note-properties').count(), 1);
    const imageData = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aVioAAAAASUVORK5CYII=';
    await page.evaluate(url => postMessage({ type: 'resolvedImage', href: 'image.png', url }, '*'), imageData);
    await page.waitForFunction(() => document.querySelector('.lp-image img')?.getAttribute('src')?.startsWith('data:'));
    assert.equal(h.text(), source);
    await page.evaluate(() => { const e = window.LivePreview; const p = e.bridge.text.indexOf('内部'); e.goto(p); });
    assert((await page.locator('.lp-strong').innerText()).includes('**外层 *内部* 文本**'));
    await page.keyboard.type('中文'); await h.idle(); assert(h.text().includes('*中文内部*'));
    await page.keyboard.press('Enter'); await h.idle(); await page.keyboard.press('Backspace'); await h.idle(); assert(h.text().includes('*中文内部*'));
    const before = h.text();
    await page.evaluate(() => { const e = window.LivePreview; e.toggleFold(e.view.state.doc.line(5).from); });
    assert.equal(await page.locator('.lp-image').count(), 0); assert.equal(h.text(), before);
    await page.evaluate(() => window.LivePreview.goto(0));
    const table = '# T\n\n| A | B |\n| --- | --- |\n| 原文 | 内容 |\n\n尾部\n';
    await h.load(table); await page.locator('.lp-table td').nth(2).click(); await page.keyboard.press('End'); await page.keyboard.type('增'); await h.idle();
    await page.keyboard.press('Control+z'); await h.idle(); await page.waitForFunction(() => window.LivePreview.cell?.view.state.doc.toString() === '原文');
    await h.change(h.text().replace('内容', '外部内容')); await page.waitForFunction(() => window.LivePreview.bridge.text.includes('外部内容'));
    assert.equal(await page.locator('.lp-cell-active .cm-content').innerText(), '原文');
    await page.locator('#reportContent > .cm-editor > .cm-scroller > .cm-content').click({ position: { x: 10, y: 10 } });
    await page.locator('.lp-cell-active').waitFor({ state: 'detached' });
    assert.equal(await page.locator('.lp-cell-active').count(), 0);
    await h.load('# H\n\n段落A\n\n段落B\n');
    await page.locator('#readerSettingsToggle').click(); await page.locator('label[for=enableBlockDrag]').click(); await page.locator('#readerSettingsToggle').click();
    await page.locator('.lp-drag').nth(2).dragTo(page.locator('.cm-line').filter({ hasText: '段落A' }), { targetPosition: { x: 70, y: 8 } });
    await h.idle(); assert(h.text().indexOf('段落B') < h.text().indexOf('段落A'));
    await page.locator('#readerSettingsToggle').click(); await page.locator('label[for=enableBlockDrag]').click(); await page.locator('#readerSettingsToggle').click();
    const long = '# 长文\n\n' + Array.from({ length: 1200 }, (_, i) => `## 第 ${i} 节\n\n段落 **内容 ${i}**。\n\n`).join('');
    await h.load(long); await page.evaluate(() => window.LivePreview.goto(window.LivePreview.bridge.text.lastIndexOf('段落')));
    await page.waitForTimeout(200);
    assert((await page.locator('#reportContent').innerText()).includes('内容 1199'));
    assert(await page.locator('.cm-line').count() < 1000, 'long documents virtualize source lines');
    assert.equal(h.text(), long);
    await page.keyboard.type('末尾修改'); await h.idle(); assert(h.text().includes('末尾修改段落 **内容 1199**'));
    assert.deepEqual(h.errors, []);
    console.log('Extended checks passed: source properties, nested marks, tasks, HTML filtering/details, definitions, footnotes, image refresh, split/join, folding, active-cell undo/external updates and 1200-section virtualization.');
  } finally { if (h.errors.length) console.log(h.errors); await h.close(); }
}
main().catch(e => { console.error(e); process.exitCode = 1; });
